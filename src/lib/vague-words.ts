/**
 * Размытые формулировки в требованиях: слово нельзя проверить без метрики или уточнения.
 * Используется генератором артефактов и линтером требований.
 * pattern — регулярное выражение (применяется с флагами 'iu'); L — «не буква» по краям слова.
 * Существительные-категории («надёжность», «безопасность») не ловим — ловим оценочные прилагательные и наречия.
 */
const L = '(?<!\\p{L})';
const R = '(?!\\p{L})';

export const VAGUE_WORDS: { pattern: string; word: string; hint: string }[] = [
  { pattern: `${L}быстр`, word: 'быстро', hint: 'укажите время: «не дольше N секунд для 95 % запросов»' },
  { pattern: `${L}медленн`, word: 'медленно', hint: 'укажите допустимое время' },
  { pattern: `${L}удобн`, word: 'удобно', hint: 'измеримый критерий: время на операцию, число шагов, без обучения' },
  { pattern: `${L}интуитивн`, word: 'интуитивно', hint: 'юзабилити-критерий: «без обучения за N минут»' },
  { pattern: `${L}понятн(ый|ая|ое|ые|ым|ой|о)${R}`, word: 'понятно', hint: 'для кого и как проверить понятность' },
  { pattern: `${L}над[её]жн(ый|ая|ое|ые|ым|ой|ого|о)${R}`, word: 'надёжно', hint: 'доступность в %, RTO / RPO, поведение при сбое' },
  { pattern: `${L}безопасн(ый|ая|ое|ые|ым|ой|ого|о)${R}`, word: 'безопасно', hint: 'конкретная мера: шифрование, роли, журнал, срок хранения' },
  { pattern: `${L}гибк`, word: 'гибко', hint: 'что именно настраивается и кем' },
  { pattern: `${L}современн`, word: 'современный', hint: 'конкретная технология или характеристика' },
  { pattern: `${L}оптимальн`, word: 'оптимально', hint: 'критерий оптимальности и его значение' },
  { pattern: `${L}эффективн`, word: 'эффективно', hint: 'метрика эффективности' },
  { pattern: `${L}просто${R}`, word: 'просто', hint: 'измеримый критерий простоты' },
  { pattern: `${L}достаточн`, word: 'достаточно', hint: 'конкретное значение' },
  { pattern: `${L}своевременн`, word: 'своевременно', hint: 'срок: к какому моменту или за какое время' },
  { pattern: `в\\s(кратчайш|разумн|сжат)\\S*\\sсрок`, word: 'в кратчайшие / разумные сроки', hint: 'конкретный срок' },
  { pattern: `${L}как можно\\s`, word: 'как можно…', hint: 'конкретное значение' },
  { pattern: `${L}(несколько|некоторы[хемй]|многи[хем]|большое количество|большого количества)${R}`, word: 'несколько / некоторые / много', hint: 'точное число или перечень' },
  { pattern: `${L}(часто|редко|обычно)${R}`, word: 'часто / редко / обычно', hint: 'частота в числах; что в остальных случаях' },
  { pattern: `${L}по возможности${R}`, word: 'по возможности', hint: 'требование или нет? Уберите или задайте условие' },
  { pattern: `${L}при необходимости${R}`, word: 'при необходимости', hint: 'кто и по какому условию решает, что необходимо' },
  { pattern: `${L}и\\s?т\\.\\s?[дп]\\.`, word: 'и т. д.', hint: 'перечислите все элементы — список должен быть закрытым' },
  { pattern: `${L}и\\sдр(\\.|уго)`, word: 'и др.', hint: 'перечислите все элементы' },
  { pattern: `${L}как правило${R}`, word: 'как правило', hint: 'а в каких случаях иначе? Опишите исключения' },
  { pattern: `${L}должным образом${R}`, word: 'должным образом', hint: 'что значит «должным»' },
  // «минимально необходимый набор: ФИО, …» — дальше закрытый перечень, это не размыто.
  { pattern: `${L}(максимально|минимально)${R}(?![^:]*:)`, word: 'максимально / минимально', hint: 'конкретная граница' },
  { pattern: `${L}(вс[еи]х?|всем) заинтересованн`, word: 'все заинтересованные', hint: 'перечислите роли: кого именно, о чём и каким каналом' },
  { pattern: `${L}вс[её] необходим`, word: 'всё необходимое', hint: 'перечислите, что именно' },
  { pattern: `${L}и\\/или${R}`, word: 'и/или', hint: 'разделите на однозначные условия' },
  { pattern: `${L}(user-friendly|красив)`, word: 'красиво / user-friendly', hint: 'субъективно — нужен проверяемый критерий' },
];

/** Найти размытые слова в тексте. */
export function findVague(text: string): { word: string; hint: string; pattern: string }[] {
  return VAGUE_WORDS.filter((v) => new RegExp(v.pattern, 'iu').test(text)).map(({ word, hint, pattern }) => ({ word, hint, pattern }));
}
