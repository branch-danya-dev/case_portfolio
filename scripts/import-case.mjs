const anchorOf = (id) => id.toLowerCase();
const prefixOf = (id) => id.replace(/-\d+$/, '');

// ---------- Утилиты mdast ----------

function walk(node, fn, parents = []) {
  if (fn(node, parents) === false) return;
  if (node.children) for (const child of [...node.children]) walk(child, fn, [...parents, node]);
}

const jsxAttr = (name, value) => ({ type: 'mdxJsxAttribute', name, value });
const span = (id) => ({ type: 'mdxJsxTextElement', name: 'span', attributes: [jsxAttr('id', id), jsxAttr('class', 'case-anchor')], children: [] });

const processor = unified().use(remarkParse).use(remarkGfm);
const serializer = unified().use(remarkGfm).use(remarkMdx).use(remarkStringify, {
  bullet: '-',
  fences: true,
  rule: '-',
  emphasis: '_',
  strong: '*',
  listItemIndent: 'one',
});

async function walkFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walkFiles(join(dir, e.name)) : [join(dir, e.name)])),
  );
  return files.flat();
}

// ---------- Разрешение путей ----------

const allFiles = (await walkFiles(SRC)).map((f) => toPosix(relative(SRC, f)));
const byBase = new Map();
for (const f of allFiles) {
  const base = posix.basename(f);
  byBase.set(base, byBase.has(base) ? null : f); // null = неоднозначно
}

function resolveRef(value, docRel) {
  const v = value.trim();
  if (/[*?]/.test(v)) return null;
  const candidates = [posix.join(posix.dirname(docRel), v), posix.normalize(v)];
  for (const c of candidates) if (allFiles.includes(c)) return c;
  const base = byBase.get(posix.basename(v));
  return base ?? null;
}

export const diagramAnchor = (rel) => posix.basename(rel).replace(/\.(puml|bpmn)$/, '');

function urlForFile(rel) {
  if (rel.endsWith('.md')) return `/${pageSlug(rel)}/`;
  if (API_PAGES[rel]) return `/${API_PAGES[rel]}/`;
  if (rel.endsWith('.puml') || rel.endsWith('.bpmn')) return `/case/diagrams/#${diagramAnchor(rel)}`;
  return `/case-files/idm-joiner-docs/${rel}`;
}

// ---------- Проход 1: разбор и индекс ID ----------

const docs = allFiles.filter((f) => f.endsWith('.md'));
const trees = new Map();
/** id → { slug, anchor } */
const idIndex = new Map();
/** rel → Set(id) якоря, которые надо поставить в этом документе */

for (const rel of docs) {
  const tree = processor.parse(await readFile(join(SRC, rel), 'utf8'));
  trees.set(rel, tree);
}

for (const [rel, tree] of trees) {
  const slug = pageSlug(rel);
  // Заголовки, начинающиеся с ID: «## ADR-001. …», «## 3. UC-01. …», «### TC-12. …»
  walk(tree, (node) => {
    if (node.type !== 'heading' || node.depth < 2) return;
    const m = toString(node).match(new RegExp(`^(?:\\d+(?:\\.\\d+)*\\.?\\s*)?((?:${ID_PREFIXES.join('|')})-\\d{1,3})\\b`));
    if (!m || HOME[prefixOf(m[1])] !== rel || idIndex.has(m[1])) return;
    idIndex.set(m[1], { slug, anchor: anchorOf(m[1]) });
    node.children.unshift(span(anchorOf(m[1])));
    node.data = { ...node.data, anchored: m[1] };
  });
  // Первая ячейка строк таблиц
  walk(tree, (node) => {
    if (node.type !== 'table') return;
    node.children.slice(1).forEach((row) => {
      const cell = row.children[0];
      const text = toString(cell).trim();
      if (!ID_FULL.test(text) || HOME[prefixOf(text)] !== rel || idIndex.has(text)) return;
      idIndex.set(text, { slug, anchor: anchorOf(text) });
      cell.children.unshift(span(anchorOf(text)));
      cell.data = { ...cell.data, anchored: text };
    });
  });
}

// ---------- Проход 2: ссылки и диаграммы ----------

function linkIds(tree, rel) {
  walk(tree, (node, parents) => {
    if (node.type === 'heading' || node.type === 'link' || node.type === 'code' || node.type === 'inlineCode') return false;
    if (node.data?.anchored) return false; // ячейка-определение не ссылается сама на себя
    if (node.type !== 'text') return;
    const parent = parents.at(-1);
    const parts = [];
    let last = 0;
    for (const m of node.value.matchAll(ID_RE)) {
      const target = idIndex.get(m[1]);
      if (!target) continue;
      if (m.index > last) parts.push({ type: 'text', value: node.value.slice(last, m.index) });
      const url = target.slug === pageSlug(rel) ? `#${target.anchor}` : `/${target.slug}/#${target.anchor}`;
      parts.push({ type: 'link', url, children: [{ type: 'text', value: m[1] }] });
      last = m.index + m[1].length;
    }
    if (!parts.length) return;
    if (last < node.value.length) parts.push({ type: 'text', value: node.value.slice(last) });
    parent.children.splice(parent.children.indexOf(node), 1, ...parts);
  });
}

function linkPaths(tree, rel) {
  walk(tree, (node, parents) => {
    if (node.type === 'link' || node.type === 'heading') return false;
    if (node.type !== 'inlineCode') return;
    const target = resolveRef(node.value, rel);
    if (!target) return;
    const parent = parents.at(-1);
    const link = { type: 'link', url: urlForFile(target), children: [{ ...node }] };
    parent.children.splice(parent.children.indexOf(node), 1, link);
  });
}

function diagramNodes(refs) {
  const nodes = [];
  const svgs = new Set(refs.filter((r) => r.endsWith('.svg')));
  for (const r of refs) {
    if (r.endsWith('.puml')) {
      nodes.push({
        type: 'mdxJsxFlowElement',
        name: 'PlantUmlDiagram',
        attributes: [jsxAttr('file', r), jsxAttr('title', posix.basename(r))],
        children: [],
      });
    } else if (r.endsWith('.bpmn')) {
      const svg = r.replace(/\.bpmn$/, '.svg');
      const attrs = [
        jsxAttr('client:visible', null),
        jsxAttr('src', `/case-files/idm-joiner-docs/${r}`),
        jsxAttr('title', posix.basename(r)),
      ];
      if (svgs.has(svg) || allFiles.includes(svg)) attrs.push(jsxAttr('previewSrc', `/case-files/idm-joiner-docs/${svg}`));
      nodes.push({ type: 'mdxJsxFlowElement', name: 'BpmnViewer', attributes: attrs, children: [] });
    }
  }
  return nodes;
}

/** Вставляет диаграммы после абзацев «Диаграмма: …» и после таблицы сценариев SEQ. */
function insertDiagrams(tree, rel) {
  const used = { plantuml: false, bpmn: false };
  const children = tree.children;
  for (let i = 0; i < children.length; i++) {
    const node = children[i];
    let refs = [];
    if (node.type === 'paragraph' && /^Диаграмм[аы]:/.test(toString(node))) {
      walk(node, (n) => {
        if (n.type === 'inlineCode') {
          const t = resolveRef(n.value, rel);
          if (t) refs.push(t);
        }
      });
    } else if (node.type === 'table' && rel === '04_integrations/02_scenarios.md') {
      // Таблица SEQ: диаграмма на каждую строку, подпись — ID и описание сценария
      const nodes = node.children.slice(1).flatMap((row) => {
        const id = toString(row.children[0]).trim();
        const title = `${id}. ${toString(row.children[1]).trim()}`;
        let file = null;
        walk(row, (n) => {
          if (n.type === 'inlineCode' && !file) file = resolveRef(n.value, rel);
        });
        if (!file?.endsWith('.puml')) return [];
        used.plantuml = true;
        return [{ type: 'mdxJsxFlowElement', name: 'PlantUmlDiagram', attributes: [jsxAttr('file', file), jsxAttr('title', title)], children: [] }];
      });
      children.splice(i + 1, 0, ...nodes);
      i += nodes.length;
      continue;
    }
    if (!refs.length) continue;
    const nodes = diagramNodes(refs);
    if (nodes.some((n) => n.name === 'PlantUmlDiagram')) used.plantuml = true;
    if (nodes.some((n) => n.name === 'BpmnViewer')) used.bpmn = true;
    children.splice(i + 1, 0, ...nodes);
    i += nodes.length;
  }
  return used;
}

