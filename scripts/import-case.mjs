/** Слаг страницы сайта для исходного .md (без слэшей по краям). */
export function pageSlug(rel) {
  if (rel === 'README.md') return 'case';
  if (rel === 'CHEATSHEET.md') return 'case/cheatsheet';
  const [layer, file] = rel.split('/');
  return `case/${LAYERS[layer].dir}/${file.replace(/^\d+_/, '').replace(/\.md$/, '')}`;
}

