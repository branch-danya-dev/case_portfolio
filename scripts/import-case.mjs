const yamlStr = (s) => JSON.stringify(s); // JSON-строка — валидный YAML

let written = 0;
for (const [rel, tree] of trees) {
  const h1Index = tree.children.findIndex((n) => n.type === 'heading' && n.depth === 1);
  const title = h1Index >= 0 ? toString(tree.children[h1Index]) : rel;
  if (h1Index >= 0) tree.children.splice(h1Index, 1);

  linkPaths(tree, rel);
  linkIds(tree, rel);
  const used = insertDiagrams(tree, rel);

  const slug = pageSlug(rel);
  const [layer, file] = rel.split('/');
  const order = rel === 'README.md' ? 0 : rel === 'CHEATSHEET.md' ? 1 : Number(file?.match(/^(\d+)_/)?.[1] ?? 99);
  const layerLabel = LAYERS[layer]?.label;
  const description =
    rel === 'README.md'
      ? 'Учебный кейс IDM-JOINER: полный комплект документации системного анализа — от устава до тест-кейсов.'
      : rel === 'CHEATSHEET.md'
        ? 'Шпаргалка к кейсу: слои проекта, этапы и артефакты, трассировка, карточки документов, разбор диаграмм.'
        : `Кейс IDM-JOINER · ${layerLabel}: ${title}.`;

  const frontmatter = [
    '---',
    `title: ${yamlStr(title)}`,
    `description: ${yamlStr(description)}`,
    'sidebar:',
    `  order: ${order}`,
    ...(SHORT[rel] ? [`  label: ${yamlStr(SHORT[rel])}`] : []),
    'tableOfContents:',
    '  maxHeadingLevel: 3',
    '---',
  ];

  // Путь импорта зависит от глубины файла: case/index.mdx → ../../../, case/cheatsheet.mdx → ../../../, case/x/y.mdx → ../../../../
  const depth = slug === 'case' ? 3 : slug.split('/').length + 1;
  const up = '../'.repeat(depth);
  const imports = [`import CaseSourceBar from '${up}components/case/CaseSourceBar.astro';`];
  if (used.plantuml) imports.push(`import PlantUmlDiagram from '${up}components/PlantUmlDiagram.astro';`);
  if (used.bpmn) imports.push(`import BpmnViewer from '${up}components/BpmnViewer.tsx';`);
  if (rel === 'README.md') imports.push(`import CaseLayers from '${up}components/case/CaseLayers.astro';`);

  const body = String(serializer.stringify(tree));
  const content = [
    ...frontmatter,
    '',
    ...imports,
    '',
    MARK,
    '',
    `<CaseSourceBar file="${rel}" />`,
    '',
    body.trim(),
    ...(rel === 'README.md' ? ['', '## Навигация по слоям', '', '<CaseLayers />'] : []),
    '',
  ].join('\n');

  const outFile = slug === 'case' ? join(OUT, 'index.mdx') : join(resolve('src/content/docs'), `${slug}.mdx`);
  if (existsSync(outFile)) {
    const prev = await readFile(outFile, 'utf8');
    if (!prev.includes('GENERATED by scripts/import-case.mjs')) {
      console.warn(`[import-case] пропущен (правлен вручную): ${outFile}`);
      continue;
    }
  }
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, content);
  written++;
}

